"""Memorial Hospital Laboratory-style synthetic PDF renderer (Epic/hospital format).

Layout follows common hospital lab reports generated by Epic and similar systems:
  - 4 columns: Test / Result / Reference Range / Units
  - Flag embedded in Result cell ("7.2 H") — no separate flag column
  - "Reference Range" (hospital/Epic default, vs Quest's "Reference Interval")
  - "Accession", "Ordering Provider", "MRN" + Age in header
  - Panel headers with gray background band
"""

from __future__ import annotations

import io
import re
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    HRFlowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from src.eval.synthesis.content_generator import BiomarkerReading, generate_readings
from src.eval.synthesis.ground_truth_writer import write_ground_truth

_CREATION_DATE_RE = re.compile(rb"/CreationDate\s*\(D:[^)]+\)")
_MOD_DATE_RE = re.compile(rb"/ModDate\s*\(D:[^)]+\)")
_PRODUCER_RE = re.compile(rb"/Producer\s*\([^)]*\)")
_CREATOR_RE = re.compile(rb"/Creator\s*\([^)]*\)")
_ID_RE = re.compile(rb"/ID\s*\[<[0-9a-fA-F]+><[0-9a-fA-F]+>\]")
_FIXED_ID = b"/ID [<00000000000000000000000000000000><00000000000000000000000000000000>]"

_PANELS: dict[str, list[str]] = {
    "BASIC METABOLIC PANEL": [
        "fasting_glucose",
        "egfr",
        "creatinine",
        "bun",
        "sodium",
        "potassium",
    ],
    "LIPID PANEL": ["total_cholesterol", "ldl_cholesterol", "hdl_cholesterol", "triglycerides"],
    "ADDITIONAL STUDIES": ["hba1c", "tsh", "vitamin_d", "hemoglobin", "wbc", "platelets"],
}

_COL_HEADERS = ["Test", "Result", "Reference Range", "Units"]
# Widths sum to 7.0 in (letter - 2 × 0.75 in margins)
_COL_WIDTHS = [3.0 * inch, 1.2 * inch, 1.8 * inch, 1.0 * inch]


def _make_reproducible(pdf_bytes: bytes) -> bytes:
    """Replace all timestamp/hash fields so output is byte-identical for same seed."""
    epoch = b"D:19700101000000+00'00'"
    pdf_bytes = _CREATION_DATE_RE.sub(b"/CreationDate (" + epoch + b")", pdf_bytes)
    pdf_bytes = _MOD_DATE_RE.sub(b"/ModDate (" + epoch + b")", pdf_bytes)
    pdf_bytes = _PRODUCER_RE.sub(b"/Producer (Vitalog Eval)", pdf_bytes)
    pdf_bytes = _CREATOR_RE.sub(b"/Creator (Vitalog Eval)", pdf_bytes)
    pdf_bytes = _ID_RE.sub(_FIXED_ID, pdf_bytes)
    return pdf_bytes


def _patient_age(collection_date: str) -> int:
    """Age in years at time of collection, relative to fixed DOB 1970-01-01."""
    dob = datetime(1970, 1, 1)
    collected = datetime.strptime(collection_date, "%Y-%m-%d")
    return (collected - dob).days // 365


def _build_pdf(
    readings: list[BiomarkerReading],
    seed: int,
    collection_date: str,
    lab_source: str,
) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=LETTER,
        leftMargin=0.75 * inch,
        rightMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.75 * inch,
    )
    styles = getSampleStyleSheet()
    normal = styles["Normal"]
    normal.fontSize = 9
    title_style = styles["h2"]

    # reportlab flowables — Any because reportlab has no type stubs
    elements: list[Any] = []

    # ── Header ───────────────────────────────────────────────────────────────
    d = datetime.strptime(collection_date, "%Y-%m-%d")
    age = _patient_age(collection_date)
    elements.append(Paragraph(f"<b>{lab_source}</b>", title_style))
    elements.append(Paragraph("123 Medical Center Drive, Anytown, CA 90000", normal))
    elements.append(Spacer(1, 0.1 * inch))
    elements.append(Paragraph("<b>LABORATORY REPORT</b>", normal))
    elements.append(Spacer(1, 0.08 * inch))

    reported_date = (d + timedelta(days=1)).strftime("%m/%d/%Y")
    info_data = [
        ["Patient:  TEST PATIENT", f"MRN:      TEST-{seed:04d}"],
        [f"Date of Birth:  01/01/1970   Age: {age}Y", "Sex:      Male"],
        ["Ordering Provider:  J. Doe, MD", "Location: Outpatient"],
        [f"Collected:  {d.strftime('%m/%d/%Y')} 08:30", f"Accession: LAB-{seed:06d}"],
        [f"Received:   {d.strftime('%m/%d/%Y')} 11:45", f"Reported:  {reported_date} 07:22"],
    ]
    info_tbl = Table(info_data, colWidths=[3.5 * inch, 3.5 * inch])
    info_tbl.setStyle(
        TableStyle(
            [
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("TOPPADDING", (0, 0), (-1, -1), 1),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
            ]
        )
    )
    elements.append(info_tbl)
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.black))
    elements.append(Spacer(1, 0.08 * inch))

    # ── Results table ────────────────────────────────────────────────────────
    # Hospital/Epic: flag embedded in Result cell, no separate flag column
    by_id = {r.vitalog_id: r for r in readings}
    table_data: list[list[str]] = [_COL_HEADERS[:]]
    panel_rows: list[int] = []

    for panel_name, vitalog_ids in _PANELS.items():
        panel_rows.append(len(table_data))
        table_data.append([panel_name, "", "", ""])
        for vid in vitalog_ids:
            if vid in by_id:
                r = by_id[vid]
                result_cell = f"{r.original_value} {r.flag}".strip() if r.flag else r.original_value
                table_data.append([r.original_name, result_cell, r.original_range, r.original_unit])

    # reportlab TableStyle commands — Any because reportlab has no type stubs
    style_cmds: list[Any] = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
    ]
    for row_idx in panel_rows:
        style_cmds.extend(
            [
                ("BACKGROUND", (0, row_idx), (-1, row_idx), colors.Color(0.88, 0.88, 0.88)),
                ("FONTNAME", (0, row_idx), (-1, row_idx), "Helvetica-Bold"),
                ("SPAN", (0, row_idx), (-1, row_idx)),
            ]
        )

    tbl = Table(table_data, colWidths=_COL_WIDTHS, repeatRows=1)
    tbl.setStyle(TableStyle(style_cmds))
    elements.append(tbl)
    elements.append(Spacer(1, 0.1 * inch))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.black))
    elements.append(Spacer(1, 0.05 * inch))

    # ── Footer ───────────────────────────────────────────────────────────────
    elements.append(
        Paragraph(
            "Abnormal results indicated with H (High) or L (Low). "
            "Result verified by: A. Smith, MD   "
            "Electronically signed: " + (d + timedelta(days=1)).strftime("%m/%d/%Y") + "   "
            "SYNTHETIC — VITALOG EVAL",
            normal,
        )
    )

    doc.build(elements)
    return _make_reproducible(buf.getvalue())


def generate_report(
    seed: int,
    out_dir: Path,
    *,
    collection_date: str | None = None,
    lab_source: str = "Memorial Hospital Laboratory",
    overrides: dict[str, str] | None = None,
) -> tuple[Path, Path]:
    """Render one synthetic hospital-style PDF + ground-truth JSON pair.

    Returns (pdf_path, ground_truth_path).
    overrides maps vitalog_id → value string for H1 hero dataset pins.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    date = collection_date or "1970-01-01"
    pdf_path = out_dir / f"synthetic_{seed:06d}.pdf"
    gt_path = out_dir / f"synthetic_{seed:06d}.ground_truth.json"

    readings = generate_readings(seed, overrides)
    pdf_bytes = _build_pdf(readings, seed, date, lab_source)
    pdf_path.write_bytes(pdf_bytes)
    write_ground_truth(gt_path, readings, date, lab_source)

    return pdf_path, gt_path
